import {isDeepStrictEqual} from 'node:util'
// Runs only from game-live.mjs after authenticated TEST admission and SDK login.
export async function validateDoudizhu(pages,check){
 if(pages.length!==6)throw Error('Dou dizhu validation requires three players and three spectators')
 const all=fn=>Promise.all(pages.map(p=>p.waitForFunction(fn,null,{timeout:40000})))
 const viewReady=()=>{const g=window.game,b=g.state?.doudizhu,v=g.doudizhuView;return b&&v&&b.players.includes(v.member)&&v.hand.length===b.counts[b.players.indexOf(v.member)]&&!g.paused}
 await all(()=>window.game.state?.players.length===3)
 // Let the normal admission refresh observe every joining member.
 await new Promise(r=>setTimeout(r,11000))
 for(const p of pages.slice(1,3)){const member=await p.evaluate(()=>window.game.me);await p.evaluate(()=>window.game.act('ready'));await p.waitForFunction(()=>!window.game.awaitingAction);await Promise.all(pages.map(q=>q.waitForFunction(id=>window.game.state.ready.includes(id),member)))}
 await all(()=>window.game.state.ready.length===3)
 await pages[0].evaluate(()=>window.game.act('start'))
 await all(()=>window.game.state?.doudizhu?.phase==='bidding')
 await all(viewReady)
 const opening=await Promise.all(pages.map(p=>p.evaluate(()=>({public:window.game.state.doudizhu,view:window.game.doudizhuView,me:window.game.me}))))
 if(opening.some(s=>s.public.bottom!==null||s.public.remaining!==null||'hands' in s.public))throw Error('private cards in public state')
 if(opening.slice(0,3).some(s=>s.view.member!==s.me||s.view.hand.length!==17))throw Error('incorrect player hand')
 if(new Set(opening.slice(0,3).flatMap(s=>s.view.hand)).size!==51)throw Error('duplicate dealt cards')
 check('doudizhu_real_three_players_three_spectators_encrypted_deal')
 const bidder=opening[0].public.turn
 await pages[bidder].evaluate(()=>window.game.act('bid',3))
 await all(()=>window.game.state?.doudizhu?.phase==='playing');await all(viewReady)
 const counts=await pages[0].evaluate(()=>window.game.state.doudizhu.counts)
 if(counts[bidder]!==20||counts.reduce((a,b)=>a+b,0)!==54)throw Error('landlord bottom cards missing')
 check('doudizhu_real_bidding_and_public_bottom')
 const target=await pages[1].evaluate(()=>window.game.me)
 for(const p of pages.slice(3))await p.evaluate(member=>window.game.watch(member),target)
 await Promise.all(pages.slice(3).map(p=>p.waitForFunction(member=>window.game.doudizhuView?.member===member,target)))
 const targetHand=await pages[1].evaluate(()=>JSON.stringify(window.game.doudizhuView.hand))
 for(const p of pages.slice(3))if(await p.evaluate(()=>JSON.stringify(window.game.doudizhuView.hand))!==targetHand)throw Error('spectator hand mismatch')
 const denied=await pages[0].evaluate(async member=>{try{await window.game.watch(member);return false}catch{return true}},target)
 if(!denied)throw Error('player accepted another hand viewpoint')
 check('doudizhu_real_spectator_view_switch_and_player_privacy')
 const before=await pages[0].evaluate(()=>JSON.stringify(window.game.state.doudizhu))
 await pages[3].evaluate(async()=>{try{await window.game.act('play',[window.game.doudizhuView.hand[0]])}catch{}})
 await new Promise(r=>setTimeout(r,1500))
 if(before!==await pages[0].evaluate(()=>JSON.stringify(window.game.state.doudizhu)))throw Error('spectator changed game')
 await pages[bidder].evaluate(()=>window.game.act('play',[window.game.doudizhuView.hand[0]]))
 await all(()=>window.game.state.doudizhu.lastCards.length===1);await all(viewReady)
 const states=await Promise.all(pages.map(p=>p.evaluate(()=>window.game.state.doudizhu)))
 if(states.some(s=>!isDeepStrictEqual(s,states[0])))throw Error('public state mismatch')
 check('doudizhu_real_play_and_consistent_public_state')
 const reconnectHand=await pages[1].evaluate(()=>JSON.stringify(window.game.doudizhuView.hand))
 await pages[1].evaluate(()=>window.game.reconnect());await pages[1].waitForFunction(viewReady)
 if(await pages[1].evaluate(()=>JSON.stringify(window.game.doudizhuView.hand))!==reconnectHand)throw Error('reconnect changed own hand')
 check('doudizhu_real_rekey_and_private_hand_restored')
 if(process.env.GAME_LIVE_READMIT==='1'){
  const previous=await pages[1].evaluate(()=>{clearInterval(window.game.timer);return {member:window.game.me,hand:window.game.doudizhuView.hand}})
  await new Promise(r=>setTimeout(r,70000))
  const deadlineBefore=await pages[0].evaluate(()=>window.game.state.doudizhu.deadline)
  await pages[1].evaluate(()=>window.game.reconnect());await pages[1].waitForFunction(viewReady,null,{timeout:40000})
  const current=await pages[1].evaluate(()=>window.game.me)
  if(current===previous.member)throw Error('expired membership was not replaced')
  if(await pages[1].evaluate(()=>JSON.stringify(window.game.doudizhuView.hand))!==JSON.stringify(previous.hand))throw Error('readmission did not restore identical hand')
  await all(()=>window.game.state.doudizhu.players.includes(window.game.me)||!window.game.state.players.includes(window.game.me))
  const hostPlayers=await pages[0].evaluate(()=>window.game.state.doudizhu.players)
  if(hostPlayers[1]!==current)throw Error('same-device readmission did not restore seat')
  if(await pages[0].evaluate(()=>window.game.state.doudizhu.deadline)!==deadlineBefore)throw Error('readmission reset the turn deadline')
  check('doudizhu_real_expired_membership_readmission_and_rekey')
 }
 await pages[2].evaluate(()=>window.game.leave())
 await Promise.all(pages.filter((_,i)=>i!==2).map(p=>p.waitForFunction(()=>window.game.state.doudizhu?.phase==='ended'&&window.game.state.doudizhu.reason==='withdraw',null,{timeout:30000})))
 check('doudizhu_real_voluntary_exit_ends_without_winner')
 await pages[0].evaluate(()=>window.game.act('next'))
 await Promise.all(pages.filter((_,i)=>i!==2).map(p=>p.waitForFunction(()=>!window.game.state.doudizhu&&window.game.state.ready.includes(window.game.room.host_membership_id))))
 check('doudizhu_real_next_round_lobby')
 // game-live's common chat check excludes the explicitly departed player.
 return pages.filter((_,i)=>i!==2)
}
