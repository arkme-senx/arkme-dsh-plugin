// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { SocialAccessStore, SOCIAL_ACCESS_TTL_MS, SOCIAL_ACCESS_READ_TIMEOUT_MS } from '../src/client/social-access-store.js'
import { SocialAccessSnapshotStorage } from '../src/client/social-access-snapshot-storage.js'

const pending = <T,>() => {
  let resolve!: (value: T) => void
  const promise = new Promise<T>(done => { resolve = done })
  return { promise, resolve }
}
beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(1_800_000_000_000); localStorage.clear() })
afterEach(() => { localStorage.clear(); vi.useRealTimers() })

describe('bounded social access cache revalidation', () => {
  it('restores freshness across reloads and fetches remotely only after expiry', async () => {
    const snapshots = new SocialAccessSnapshotStorage()
    const first = new SocialAccessStore(async () => ({ userId: 7, allowed: true }), snapshots)
    first.activate('test:7'); first.confirm('test:7', true)
    const load = vi.fn(async () => ({ userId: 7, allowed: false }))
    const restored = new SocialAccessStore(load, snapshots)
    restored.activate('test:7')
    await restored.refreshIfStale(); expect(load).not.toHaveBeenCalled()
    vi.advanceTimersByTime(SOCIAL_ACCESS_TTL_MS)
    await restored.refreshIfStale()
    expect(load).toHaveBeenCalledExactlyOnceWith(expect.any(AbortSignal), true)
    expect(restored.getSnapshot().allowed).toBe(false)
  })
  it('uses legacy cache as stale history and hydrates a missing cache from the local profile', async () => {
    const snapshots = new SocialAccessSnapshotStorage()
    localStorage.setItem('arkme.social-access.presentation.v1:test:7', 'true')
    const load = vi.fn(async (_signal: AbortSignal, remote: boolean) => ({ userId: 7, allowed: true, checkedAtMillis: remote ? Date.now() : 0 }))
    const legacy = new SocialAccessStore(load, snapshots)
    legacy.activate('test:7'); expect(legacy.getSnapshot().allowed).toBe(true)
    await legacy.refreshIfStale(); expect(load.mock.calls[0]?.[1]).toBe(true)
    const cold = new SocialAccessStore(load)
    cold.activate('test:7'); await cold.refreshIfStale(); expect(load.mock.lastCall?.[1]).toBe(false)
    expect(cold.getSnapshot().allowed).toBe(true)
    await cold.refreshIfStale(); expect(load.mock.lastCall?.[1]).toBe(true)
  })
  it.each([true, false])('retains %s and its age on failure, with a bounded retry cooldown', async allowed => {
    const snapshots = new SocialAccessSnapshotStorage()
    const load = vi.fn(async () => { throw new Error('offline') })
    const store = new SocialAccessStore(load, snapshots)
    store.activate('test:7'); store.confirm('test:7', allowed)
    const before = snapshots.readConfirmation('test:7')
    vi.advanceTimersByTime(SOCIAL_ACCESS_TTL_MS)
    await store.refreshIfStale()
    for (let i = 0; i < 20; i++) await store.refreshIfStale()
    expect(load).toHaveBeenCalledTimes(1)
    expect(snapshots.readConfirmation('test:7')).toEqual(before)
    expect(store.getSnapshot().allowed).toBe(allowed)
    vi.advanceTimersByTime(5_000); await store.refreshIfStale()
    expect(load).toHaveBeenCalledTimes(2)
    vi.advanceTimersByTime(5_000); await store.refreshIfStale()
    expect(load).toHaveBeenCalledTimes(2)
  })
  it('releases a hung flight at the deadline, aborts its signal and ignores the late result', async () => {
    const first = pending<{ userId: number; allowed: boolean }>()
    const load = vi.fn((_signal: AbortSignal) => first.promise)
    const store = new SocialAccessStore(load)
    store.activate('test:7'); store.confirm('test:7', true)
    const attempt = store.refresh()
    expect(store.refresh()).toBe(attempt)
    await vi.advanceTimersByTimeAsync(SOCIAL_ACCESS_READ_TIMEOUT_MS)
    await attempt
    expect(load.mock.calls[0]![0].aborted).toBe(true)
    load.mockResolvedValueOnce({ userId: 7, allowed: true })
    await store.refresh()
    first.resolve({ userId: 7, allowed: false }); await first.promise; await Promise.resolve()
    expect(store.getSnapshot().allowed).toBe(true)
    expect(load).toHaveBeenCalledTimes(2)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('local binding supersedes a pending unbound response and immediately updates another window', async () => {
    const snapshots = new SocialAccessSnapshotStorage()
    const old = pending<{ userId: number; allowed: boolean }>()
    const store = new SocialAccessStore(() => old.promise, snapshots)
    const other = new SocialAccessStore(async () => ({ userId: 7, allowed: false }), snapshots)
    store.activate('test:7'); store.confirm('test:7', false); other.activate('test:7')
    const attempt = store.refresh()
    store.confirm('test:7', true)
    other.syncStoredConfirmation()
    expect(other.getSnapshot().allowed).toBe(true)
    old.resolve({ userId: 7, allowed: false }); await attempt
    expect(store.getSnapshot().allowed).toBe(true)
    expect(snapshots.read('test:7')).toBe(true)
  })
  it('owns one foreground scheduler across mounts and cleans up after the last consumer', async () => {
    const load = vi.fn(async () => ({ userId: 7, allowed: true }))
    const store = new SocialAccessStore(load)
    store.activate('test:7'); store.confirm('test:7', true)
    const stop1 = store.startRevalidation(), stop2 = store.startRevalidation()
    expect(vi.getTimerCount()).toBe(1)
    await vi.advanceTimersByTimeAsync(SOCIAL_ACCESS_TTL_MS)
    expect(load).toHaveBeenCalledTimes(1)
    stop1(); expect(vi.getTimerCount()).toBe(1)
    stop2(); expect(vi.getTimerCount()).toBe(0)
    window.dispatchEvent(new Event('focus')); window.dispatchEvent(new Event('online'))
    await vi.advanceTimersByTimeAsync(SOCIAL_ACCESS_TTL_MS)
    expect(load).toHaveBeenCalledTimes(1)
  })
  it('does not overwrite another window binding when no storage listener is mounted', async () => {
    const snapshots = new SocialAccessSnapshotStorage()
    const old = pending<{ userId: number; allowed: boolean }>()
    const store = new SocialAccessStore(() => old.promise, snapshots)
    store.activate('test:7'); store.confirm('test:7', false)
    const attempt = store.refresh()
    snapshots.write('test:7', true)
    old.resolve({ userId: 7, allowed: false })
    await attempt
    expect(store.getSnapshot().allowed).toBe(true)
    expect(snapshots.read('test:7')).toBe(true)
  })
  it('pauses periodic work when hidden and refreshes expired state on return', async () => {
    const visibility = vi.spyOn(document, 'visibilityState', 'get')
    visibility.mockReturnValue('visible')
    const load = vi.fn(async () => ({ userId: 7, allowed: true }))
    const store = new SocialAccessStore(load)
    store.activate('test:7'); store.confirm('test:7', true)
    const stop = store.startRevalidation()
    try {
      visibility.mockReturnValue('hidden'); document.dispatchEvent(new Event('visibilitychange'))
      await vi.advanceTimersByTimeAsync(SOCIAL_ACCESS_TTL_MS * 2)
      expect(load).not.toHaveBeenCalled()
      visibility.mockReturnValue('visible'); document.dispatchEvent(new Event('visibilitychange'))
      await store.refreshIfStale()
      expect(load).toHaveBeenCalledTimes(1)
    } finally { stop(); visibility.mockRestore() }
  })
})
