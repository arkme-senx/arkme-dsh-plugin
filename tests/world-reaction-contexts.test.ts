import { afterEach, describe, expect, it, vi } from 'vitest'
import { ArkmeClientError } from '../src/client/api.js'
import { WorldReactionContexts } from '../src/client/world-reactions.js'
import { WORLD_REACTION_PENDING, type WorldReactionContextPage } from '../src/world-reaction-contract.js'
afterEach(() => vi.useRealTimers())
const page = (refs: string[]): WorldReactionContextPage => ({ items: refs.map(recordRef => ({ recordRef, target: { id: `world:${recordRef}`, worldRecordRef: `context:${recordRef}` }, visibility: 'published' })), unavailableRecordRefs: [] })
describe('World context batching and lifecycle', () => {
  it('batches cards, remembers missing backend support and retries only on user demand', async () => {
    vi.useFakeTimers()
    const prepare = vi.fn(async (_scope: string, refs: string[]) => page(refs))
    prepare.mockRejectedValueOnce(new ArkmeClientError({ code: 'world-reactions-unavailable', message: WORLD_REACTION_PENDING, retryable: false }))
    const contexts = new WorldReactionContexts(prepare)
    contexts.setScope('test:1')
    const a = contexts.watch('test:1', 'a'), b = contexts.watch('test:1', 'b')
    await vi.advanceTimersByTimeAsync(50)
    expect(prepare).toHaveBeenCalledTimes(1)
    expect(prepare.mock.calls[0]?.[1]).toEqual(['a', 'b'])
    expect(contexts.state('test:1', 'a')?.status).toBe('unsupported')
    const c = contexts.watch('test:1', 'c')
    await vi.advanceTimersByTimeAsync(60_000)
    expect(prepare).toHaveBeenCalledTimes(1)
    contexts.retry('test:1', 'a'); await vi.advanceTimersByTimeAsync(50)
    expect(contexts.state('test:1', 'a')?.status).toBe('ready')
    expect(contexts.state('test:1', 'b')?.status).toBe('unsupported')
    a(); b(); c(); contexts.setScope(undefined)
  })
  it('discards a late response after an account switch', async () => {
    vi.useFakeTimers()
    let finish!: (value: WorldReactionContextPage) => void
    const contexts = new WorldReactionContexts(async () => await new Promise(resolve => { finish = resolve }))
    contexts.setScope('test:1'); contexts.watch('test:1', 'a')
    await vi.advanceTimersByTimeAsync(50)
    contexts.setScope('test:2'); finish(page(['a'])); await Promise.resolve()
    expect(contexts.state('test:1', 'a')).toBeUndefined()
    expect(contexts.state('test:2', 'a')).toBeUndefined()
    contexts.setScope(undefined)
  })
  it('revokes a precise card without changing another card', async () => {
    vi.useFakeTimers()
    const contexts = new WorldReactionContexts(async (_scope, refs) => page(refs))
    contexts.setScope('test:1'); contexts.watch('test:1', 'a'); contexts.watch('test:1', 'b')
    await vi.advanceTimersByTimeAsync(50)
    contexts.unavailable('test:1', 'world:a')
    expect(contexts.state('test:1', 'a')?.status).toBe('unavailable')
    expect(contexts.state('test:1', 'b')?.status).toBe('ready')
    contexts.setScope(undefined)
  })
  it('rechecks an unavailable context after reopening a freshly republished card', async () => {
    vi.useFakeTimers()
    const prepare = vi.fn(async (_scope: string, refs: string[]) => page(refs))
    const contexts = new WorldReactionContexts(prepare)
    contexts.setScope('test:1')
    const stop = contexts.watch('test:1', 'a'); await vi.advanceTimersByTimeAsync(50)
    contexts.unavailable('test:1', 'world:a'); stop()
    contexts.watch('test:1', 'a'); await vi.advanceTimersByTimeAsync(50)
    expect(contexts.state('test:1', 'a')?.status).toBe('ready')
    expect(prepare).toHaveBeenCalledTimes(2)
    contexts.setScope(undefined)
  })
})
