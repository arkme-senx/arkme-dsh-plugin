import { afterEach, expect, it, vi } from 'vitest'
import { TimelineRefreshScheduler } from '../src/client/timeline-refresh-scheduler.js'

afterEach(() => vi.useRealTimers())
it('coalesces 1000 hints behind a read and does not postpone the trailing refresh', () => {
  vi.useFakeTimers()
  const refresh = vi.fn()
  const queue = new TimelineRefreshScheduler(refresh)
  const finish = queue.begin(true)
  for (let n = 0; n < 1000; n++) queue.request()
  expect(vi.getTimerCount()).toBe(0)
  finish()
  expect(vi.getTimerCount()).toBe(1)
  vi.advanceTimersByTime(200)
  queue.request()
  vi.advanceTimersByTime(50)
  expect(refresh).toHaveBeenCalledTimes(1)
  expect(vi.getTimerCount()).toBe(0)
})
it('waits for concurrent pagination and preserves its pending refresh', () => {
  vi.useFakeTimers()
  const refresh = vi.fn(), queue = new TimelineRefreshScheduler(refresh)
  queue.request()
  const older = queue.begin(false), newer = queue.begin(false)
  older(); older()
  vi.advanceTimersByTime(1000)
  expect(refresh).not.toHaveBeenCalled()
  newer()
  vi.advanceTimersByTime(250)
  expect(refresh).toHaveBeenCalledTimes(1)
})
it('consumes old demand when an explicit current-window read starts', () => {
  vi.useFakeTimers()
  const refresh = vi.fn(), queue = new TimelineRefreshScheduler(refresh)
  queue.request()
  queue.begin(true)()
  vi.advanceTimersByTime(1000)
  expect(refresh).not.toHaveBeenCalled()
})
it('bounds race retries without a new revision', () => {
  vi.useFakeTimers()
  const refresh = vi.fn(), queue = new TimelineRefreshScheduler(refresh)
  for (let i = 0; i < 2; i++) { expect(queue.retry('revision-1')).toBe(true); vi.advanceTimersByTime(250) }
  expect(queue.retry('revision-1')).toBe(false)
  vi.advanceTimersByTime(10000)
  expect(refresh).toHaveBeenCalledTimes(2)
  expect(queue.retry('revision-2')).toBe(true)
  queue.reset()
  expect(vi.getTimerCount()).toBe(0)
})
it('cancels queued work and ignores late completions after a scope change', () => {
  vi.useFakeTimers()
  const refresh = vi.fn(), queue = new TimelineRefreshScheduler(refresh)
  const oldFinish = queue.begin(true)
  queue.request(); queue.reset()
  const newFinish = queue.begin(true)
  queue.request(); oldFinish()
  vi.advanceTimersByTime(1000)
  expect(refresh).not.toHaveBeenCalled()
  newFinish(); vi.advanceTimersByTime(250)
  expect(refresh).toHaveBeenCalledTimes(1)
  queue.request(); queue.reset()
  vi.advanceTimersByTime(1000)
  expect(refresh).toHaveBeenCalledTimes(1)
})
