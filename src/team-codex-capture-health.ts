import { createHash } from 'node:crypto'
import { lstatSync, readFileSync, realpathSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, isAbsolute, join } from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import type { TeamCodexTask } from './team-codex-contract.js'

type Json = Record<string, unknown>
const object = (value: unknown): Json => value !== null && typeof value === 'object' && !Array.isArray(value) ? value as Json : {}
function json(path: string): Json {
  const stat = lstatSync(path)
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > 524288) throw Error('Invalid capture metadata')
  return object(JSON.parse(readFileSync(path, 'utf8')))
}

/** Parse only static shell words generated by our enrollment helper. Never execute a Hook. */
export function codexCaptureCommand(command: unknown): { directory: string; installation: string; homeKey: string } | undefined {
  if (typeof command !== 'string' || command.length > 16384) return
  const words: string[] = []; let word = '', quote = '', started = false
  for (const char of command) {
    if (quote) { if (char === quote) quote = ''; else word += char; started = true }
    else if (char === "'" || char === '"') { quote = char; started = true }
    else if (/\s/.test(char)) { if (started) { words.push(word); word = ''; started = false } }
    else { if (/[`$;|&<>\\]/.test(char)) return; word += char; started = true }
  }
  if (quote) return
  if (started) words.push(word)
  if (words.length !== 6 || !isAbsolute(words[1]!) || !words[1]!.endsWith('/bridge.py') || words[2] !== 'capture'
    || !/^[0-9a-f-]{36}$/.test(words[3]!) || words[4] !== '--home-key' || !/^[a-f0-9]{64}$/.test(words[5]!)) return
  return { directory: dirname(words[1]!), installation: words[3]!, homeKey: words[5]! }
}

/** Reads only explicitly configured source metadata, never searches for or reads conversations.
 * A preview can diagnose the already configured desktop source without owning its journal.
 * Cloud task/source, owner, team and Codex home must all match before returning evidence.
 */
export class TeamCodexCaptureHealthReader {
  constructor(private readonly home = process.env.CODEX_HOME || join(homedir(), '.codex'), private readonly now = Date.now) {}
  annotate(owner: number, team: string, tasks: TeamCodexTask[]): TeamCodexTask[] {
    const health = new Map<string, NonNullable<TeamCodexTask['captureHealth']>>()
    try {
      if (lstatSync(this.home).isSymbolicLink()) return tasks
      const homeKey = createHash('sha256').update(realpathSync(this.home)).digest('hex')
      const hooks = object(json(join(this.home, 'hooks.json')).hooks)
      const commands = new Map<string, { directory: string; installation: string; homeKey: string; events: Set<string> }>()
      for (const event of ['UserPromptSubmit', 'Stop', 'Interrupt']) {
        const groups = hooks[event]
        if (!Array.isArray(groups)) continue
        for (const group of groups) for (const hook of Array.isArray(object(group).hooks) ? object(group).hooks as unknown[] : []) {
          const parsed = codexCaptureCommand(object(hook).command)
          if (!parsed || parsed.homeKey !== homeKey) continue
          const key = `${parsed.directory}/${parsed.installation}`
          const entry = commands.get(key) ?? { ...parsed, events: new Set<string>() }
          entry.events.add(event); commands.set(key, entry)
        }
      }
      if (commands.size > 8) return tasks
      for (const entry of commands.values()) {
        if (entry.events.size !== 3) continue
        let db: DatabaseSync | undefined
        try {
          const path = join(entry.directory, 'journal.sqlite')
          if (lstatSync(entry.directory).isSymbolicLink()) continue
          for (const suffix of ['', '-wal', '-shm']) {
            try { const stat = lstatSync(path + suffix); if (stat.isSymbolicLink() || !stat.isFile()) throw Error('Invalid journal') }
            catch (error) { if (suffix && (error as NodeJS.ErrnoException).code === 'ENOENT') continue; throw error }
          }
          db = new DatabaseSync(path, { readOnly: true })
          db.exec('PRAGMA query_only=ON; PRAGMA trusted_schema=OFF; PRAGMA busy_timeout=50')
          const installation = db.prepare('SELECT status,updated_at FROM codex_installations WHERE id=? AND user_id=? AND team_ref=? AND home_key=?')
            .get(entry.installation, owner, team, homeKey)
          if (!installation) continue
          const now = this.now()
          let status: NonNullable<TeamCodexTask['captureHealth']>['status'] = 'offline'
          if (installation.status !== 'active') status = 'paused'
          else {
            let active: Json = {}, lease: Json = {}
            try { active = json(join(entry.directory, 'active.json')) } catch { /* offline */ }
            try { lease = json(join(entry.directory, 'capture-lease.json')) } catch { /* old runtime */ }
            if (active.userId === owner && typeof active.at === 'number' && now >= active.at && now - active.at < 15000) status = 'online'
            else if ((!active.userId || active.userId === owner) && lease.userId === owner && typeof lease.at === 'number'
              && typeof lease.expiresAt === 'number' && now >= lease.at && now - lease.at <= 600000 && now <= lease.expiresAt) status = 'buffering'
          }
          for (const task of tasks) {
            if (task.cloud && task.cloud.ownerRef !== String(owner)) continue
            const row = task.cloud
              ? db.prepare(`SELECT t.updated_at FROM codex_tasks t JOIN codex_cloud_tasks c ON c.local_id=t.id
                  JOIN codex_cloud_sources s ON s.id=c.source WHERE t.installation_id=? AND c.id=? AND s.id=? AND s.owner=? AND s.local_team=?`)
                .get(entry.installation, task.cloud.taskId, task.cloud.sourceId, owner, team)
              : db.prepare('SELECT updated_at FROM codex_tasks WHERE installation_id=? AND id=?').get(entry.installation, task.id)
            if (row) health.set(task.id, { status, checkedAt: now, lastReceivedAt: Number(row.updated_at) })
          }
        } catch { /* Unknown evidence stays unknown; an old message alone never proves disconnection. */ }
        finally { db?.close() }
      }
    } catch { /* Unsupported/absent Hooks configuration. */ }
    return tasks.map(task => health.has(task.id) ? { ...task, captureHealth: health.get(task.id)! } : task)
  }
}
