// Only application-owned Team copy enters this function, never user messages.
export function teamText(source: string, values?: Record<string,string|number>): string {
 const copy = getArkmeLocale() === 'en' ? english[source] ?? tr(source) : source
 return values ? copy.replace(/\{(\w+)\}/g, (match,key:string) => Object.hasOwn(values,key) ? String(values[key]) : match) : copy
}
