declare module '@deepseek-ai/dsh-client-ui-slots' {
  interface LocaleNamespaceMap {
    'arkme.login': ArkmeLoginLocaleKey
  }
}

export type ArkmeLoginTranslate = TranslateNS<typeof ARKME_LOGIN_LOCALE_NAMESPACE>

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (params === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (
    name in params ? String(params[name]) : match
  ))
}

export const defaultArkmeLoginTranslate: ArkmeLoginTranslate = ((key: ArkmeLoginLocaleKey, params?: Record<string, string | number>) => (
  interpolate(arkmeLoginZh[key], params)
)) as ArkmeLoginTranslate
